"""Renders `synthetic/README.md`: a one-page overview of the generated data.

Generated from the same validated objects as everything else, so it never goes
out of date: change the content or the seed, re-run, and the overview follows.
"""

from __future__ import annotations

from collections import Counter
from datetime import date

from . import games
from .kitman_docs import _date, name
from .schema import POSITION_LABELS, REFEREE_ROLE_LABELS, STAFF_ROLE_LABELS, MatchInfo, Universe
from .scout import age_on, format_eur, ordinal
from .validate import CheckResult


def grid_table(u: Universe, m: MatchInfo) -> list[str]:
    """The example Tiki-Taka-Toe grid as a Markdown table (every valid answer in every cell)."""
    excluded = {m.home_team_id, m.guest_team_id}
    squad = [p for p in u.players if p.club_id in excluded]
    crit = games.criteria(squad, excluded)
    crit = {k: v for k, v in crit.items() if k != ("nationality", u.meta.country)}
    grid = games.example_grid(crit)
    if grid is None:
        return ["No example grid found."]
    rows, cols = grid
    clubs = {c.id: c.name for c in u.clubs}
    players = {p.id: p for p in squad}

    def label(c):
        return clubs[c[1]] if c[0] == "club" else c[1]

    out = ["| | " + " | ".join(f"**{label(c)}**" for c in cols) + " |", "|---|" + "---|" * len(cols)]
    for r in rows:
        cells = []
        for c in cols:
            ans = sorted(games.answers(crit, r, c), key=lambda pid: (players[pid].club_id, players[pid].shirt_number))
            cells.append(", ".join(f"{name(players[pid])} ({players[pid].club_id})" for pid in ans))
        out.append(f"| **{label(r)}** | " + " | ".join(cells) + " |")
    return out


def render_overview(u: Universe, m: MatchInfo, results: list[CheckResult]) -> str:
    clubs = {c.id: c for c in u.clubs}
    details = {d.club_id: d for d in u.club_details}
    players = {p.id: p for p in u.players}
    officials = {o.id: o for o in u.officials}
    staff = {s.id: s for s in u.staff}
    stadium = next(s for s in u.stadiums if s.id == m.environment.stadium_id)
    kickoff = date.fromisoformat(m.planned_kickoff[:10])
    comp = next(c for c in u.competitions if c.id == m.competition_id)
    table = next(s for s in u.standings if s.competition_id == m.competition_id)
    rows = {r.club_id: r for r in table.rows}
    h2h = next(h for h in u.head_to_head if {h.club_a, h.club_b} == {m.home_team_id, m.guest_team_id})
    home, guest = clubs[m.home_team_id], clubs[m.guest_team_id]
    counts = Counter(r.status for r in results)

    def official(role: str) -> str:
        return name(officials[next(x.official_id for x in m.officials if x.role == role)])

    def captain(cid: str) -> str:
        p = next(p for p in u.players if p.club_id == cid and p.captaincy == "captain")
        return f"#{p.shirt_number} {name(p)}"

    def top_scorer(cid: str) -> str:
        squad = [p for p in u.players if p.club_id == cid]
        best = max(p.this_season.goals for p in squad)
        names = [name(p) for p in squad if p.this_season.goals == best]
        return f"{' and '.join(names)}, {best} goal{'s' if best != 1 else ''}" if best else "no goals yet"

    def youngest(cid: str) -> str:
        p = max((p for p in u.players if p.club_id == cid), key=lambda p: p.date_of_birth)
        return f"{name(p)}, {age_on(p.date_of_birth, kickoff)}"

    def coach(cid: str) -> str:
        s = staff[details[cid].head_coach.staff_id]
        return f"{name(s)} ({s.nationality}, since {s.since})"

    out = [
        "# Synthetic data: overview",
        "",
        "> **Everything in this folder is invented.** The country, clubs, places and people are fictional; any "
        "resemblance to real ones is coincidental (nationalities and birthplaces abroad use real country and city "
        "names). This page is generated by `generator/` from the same data as the app, so it is always up to date.",
        "",
        f"**Status:** universe `{u.meta.universe_id}`, seed {u.meta.seed}. Validation: {counts['fail']} fail, "
        f"{counts['warn']} warn, {counts['pass']} pass ([report](../reports/synthetic/universe/README.md)). "
        "Still missing: the match itself: events, tracking, crowd noise (task S-4).",
        "",
        "## Files",
        "",
        "| File | What it is |",
        "|---|---|",
        "| [`universe/universe.json`](universe/universe.json) | the whole universe: clubs, roll of honour, squads with careers, transfer fees and attributes 1-99, staff, coaching history, officials, stadium, results, tables, top scorers, match preview |",
        f"| [`{m.match_id}/match_info.json`]({m.match_id}/match_info.json) | the match: line-ups with English position codes, coaches and bench staff, officials, stadium capacity and tickets sold, weather forecast, the crest and kit files of each team (DFL `matchinformation` structure) |",
        f"| [`{m.match_id}/kitman/`]({m.match_id}/kitman/) | the knowledge base of the Kit Man agent, one document per topic |",
        "| [`schema/`](schema/) | JSON Schema of the two files |",
        "",
        "## The match",
        "",
        f"**{home.name} v {guest.name}**: {h2h.name}.",
        "",
        f"- {comp.name}, season {m.season}, matchday {m.matchday}; kick-off {m.planned_kickoff[11:16]} on "
        f"{kickoff:%A} {_date(kickoff)}.",
        f"- {stadium.name}, {stadium.town}: {stadium.capacity:,} seats, {m.environment.tickets_sold:,} tickets sold.",
        f"- Weather: {m.environment.weather.temperature_c} °C at kick-off, {m.environment.weather.wind}; chance of light "
        f"rain rising to {max(f.chance_of_rain_pct for f in m.environment.forecast)}% by full time.",
        f"- Referee: {official('referee')}; VAR: {official('video_assistant_referee')}.",
        f"- Derby record: {h2h.all_time['played']} games, {home.short_name} {h2h.all_time[f'{home.id}_wins']} wins, "
        f"{guest.short_name} {h2h.all_time[f'{guest.id}_wins']}, {h2h.all_time['draws']} draws. {h2h.last_meeting.summary}",
        "",
        "| | " + " | ".join(c.name for c in (home, guest)) + " |",
        "|---|---|---|",
        "| Nickname | " + " | ".join(c.nickname for c in (home, guest)) + " |",
        "| Founded | " + " | ".join(f"{c.founded}, {c.town}" for c in (home, guest)) + " |",
        "| Colours | " + " | ".join(details[c.id].colour_names for c in (home, guest)) + " |",
        "| Chairman | " + " | ".join(name(details[c.id].chairman) for c in (home, guest)) + " |",
        "| League before kick-off | " + " | ".join(
            f"{ordinal(rows[c.id].position)}, {rows[c.id].points} pts, form {rows[c.id].form}" for c in (home, guest)) + " |",
        "| Last season | " + " | ".join(ordinal(details[c.id].last_season.position) for c in (home, guest)) + " |",
        "| League titles | " + " | ".join(str(next((len(h.seasons) for h in details[c.id].honours
                                                       if h.competition == "Meridian League"), 0)) for c in (home, guest)) + " |",
        "| Head coach | " + " | ".join(coach(c.id) for c in (home, guest)) + " |",
        "| Job security | " + " | ".join(details[c.id].head_coach.job_security.level.replace("_", " ") for c in (home, guest)) + " |",
        "| Formation | " + " | ".join(details[c.id].formation for c in (home, guest)) + " |",
        "| Style | " + " | ".join(details[c.id].playing_style for c in (home, guest)) + " |",
        "| Club captain | " + " | ".join(captain(c.id) for c in (home, guest)) + " |",
        "| Penalty taker | " + " | ".join(name(players[details[c.id].set_pieces.penalties[0]]) for c in (home, guest)) + " |",
        "| Top scorer this season | " + " | ".join(top_scorer(c.id) for c in (home, guest)) + " |",
        "| Youngest in the squad | " + " | ".join(youngest(c.id) for c in (home, guest)) + " |",
        "",
        "### Starting line-ups",
        "",
    ]
    for team in m.teams:
        starters = [e for e in team.lineup if e.starting]
        out.append(f"- **{clubs[team.team_id].name}** ({team.formation}): " + "; ".join(
            f"{players[e.player_id].last_name}, {POSITION_LABELS[e.playing_position]}{' (captain)' if e.captain else ''}"
            for e in starters) + ".")
    out += ["", "The substitutes, the players not selected (with the reason), the team news and the full squads with "
            f"careers are in the Kit Man documents [`matchday.md`]({m.match_id}/kitman/matchday.md), "
            f"[`squad-{home.id}.md`]({m.match_id}/kitman/squad-{home.id}.md) and "
            f"[`squad-{guest.id}.md`]({m.match_id}/kitman/squad-{guest.id}.md).", ""]

    out += ["## The stadium", "", f"{stadium.name}, opened {stadium.opened}. {stadium.history}", "",
            "| Stand | Side | Seats | Notes |", "|---|---|---|---|"]
    out += [f"| {st.name} | {st.side} | {sum(s.capacity for s in st.sectors):,} | {st.description} |" for st in stadium.stands]
    points = Counter()
    for s in stadium.services:
        points[s.type] += len(s.near)
    out += ["", f"{len(stadium.gates)} gates; {points['food']} food kiosk locations, {points['first_aid']} first-aid points, "
            "a sensory room, audio-described commentary, free water refill. "
            f"Getting there: {', '.join(t.mode for t in stadium.transport)}.", ""]

    out += [f"## The league: {u.meta.country}", "", u.meta.country_note, ""]
    for cp in u.competitions:
        st = next(s for s in u.standings if s.competition_id == cp.id)
        top = ", ".join(f"{r.position}. {clubs[r.club_id].short_name} ({r.points})" for r in st.rows[:3])
        out.append(f"- **{cp.name}** ({cp.clubs} clubs): after matchday {st.after_round}, top three: {top}.")
    ts = u.top_scorers[0]
    everyone = players | {lp.id: lp for lp in u.league_players}
    leaders = [r for r in ts.rows if r.rank == 1]
    out.append(f"- Top scorer{'s' if len(leaders) > 1 else ''} of the {comp.name}: " + ", ".join(
        f"{name(everyone[r.player_id])} ({clubs[r.club_id].short_name}, {r.goals})" for r in leaders) + ".")
    out += ["", "| Club | Nickname | Town | Stadium | Division |", "|---|---|---|---|---|"]
    names = {cp.id: cp.name for cp in u.competitions}
    out += [f"| {c.name} | {c.nickname} | {c.town} | {c.stadium.name} ({c.stadium.capacity:,}) | {names[c.competition_id]} |"
            for c in sorted(u.clubs, key=lambda c: (c.competition_id, c.name))]

    staff_roles = ", ".join(STAFF_ROLE_LABELS[r] for r in dict.fromkeys(s.role for s in u.staff)).lower()
    nats = Counter(p.nationality for p in u.players)
    fees = [sp.fee_eur for p in u.players for sp in p.career if sp.move == "transfer"]
    out += ["", "## In numbers", "",
            f"- {len(u.clubs)} clubs, {len(u.players)} squad players ({len(nats)} nationalities, "
            f"{nats.get(u.meta.country, 0)} from {u.meta.country}; " + ", ".join(
                f"{n} {k}" for n, k in nats.most_common() if n != u.meta.country and k >= 4) + "), "
            f"{len(u.staff)} staff ({staff_roles}), {len(u.officials)} match officials, {len(u.coaches)} other head coaches "
            f"in the coaching history, {len(u.league_players)} leading scorers of other clubs.",
            f"- {sum(len(p.career) for p in u.players)} career spells; {len(fees)} transfers from "
            f"{format_eur(min(fees))} to {format_eur(max(fees))} (all fees in euros; loans, free transfers and academy "
            f"promotions are 0); {len(u.results)} results already played.",
            f"- Officials of {m.match_id}: " + ", ".join(
                f"{REFEREE_ROLE_LABELS[o.role].lower()} {name(officials[o.official_id])}" for o in m.officials) + ".",
            "", "## Tiki-Taka-Toe", "",
            "Criteria are only the clubs of a player's career (not the two match clubs) and nationalities; the valid "
            "answers are the 50 players of the two squads. Example grid (every cell lists all valid answers):", ""]
    out += grid_table(u, m)
    out += ["", "## How it is made", "",
            "- **Hand-written** (in `generator/insidethegame_gen/content/`): clubs, stadium, staff, club history, "
            "chairmen, crests, records, coach profiles, legends, traditions, the roll of honour, the building blocks of "
            "player profiles (nicknames, styles, curiosities), the match programme and forecast, the rules guide.",
            "- **Generated with a fixed seed**: player names, ages, birthplaces, careers and transfer fees, the coaching "
            "history, fixtures, results, tables, the season simulation (minutes, goals, assists, cards, injuries, bans), "
            "line-ups, top scorers, team news and key duels. Generated because they must add up.",
            f"- **Checked before writing**: {len(results)} checks, including the surname rule, the line-ups against the "
            "formations, the Tiki-Taka-Toe crossings and a blocklist of real people, clubs, stadiums and brands and of "
            "alcohol, betting and tobacco words. If a check fails, nothing is written.",
            "- **Calibrated on real data**: player attributes 1-99, our own scale. A number is a percentile among "
            "players of the same position group on aggregated DFL data (Bassek et al., 2025, CC-BY 4.0): a winger with "
            "pace 90 reaches about the DFL p90 top speed of wingers. What each number means in km/h, metres and m/s is "
            "in the [report](../reports/synthetic/universe/README.md#attributes-1-99). No real data is stored here.",
            ""]
    return "\n".join(out)
