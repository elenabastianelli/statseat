"""The README of `synthetic/<match_id>/tickets/`, written for the judges.

It is the only place with plain codes: every DEMO code, plus the silver and gold
samples, which are printed on the sample images anyway. All other codes exist only as hashes.
"""

from __future__ import annotations

from .registry import SECTOR_TYPE_LABEL, TIERS, MatchContext, Ticket
from .render import PNG_SIZE, H, W

MODE_TEXT = {("analyst", "casual"): "Analyst, can switch to Fan", ("casual",): "Fan only"}


def seat_text(t: Ticket) -> str:
    s = t.seat
    return f"Gate {s.gate} · {s.stand} · sector {s.sector} · row {s.row} · seat {s.seat}"


def files_text(t: Ticket) -> str:
    if not t.files:
        return "–"
    return " · ".join(f"[{fmt.upper()}]({path})" for fmt, path in t.files.items())


def tier_seats(tickets: list[Ticket], tier: str) -> str:
    seats = [t.seat for t in tickets if t.tier.name == tier]
    sectors = sorted({s.sector for s in seats}, key=lambda x: (x[0], int(x[1:]) if x[1:].isdigit() else 0))
    stands = sorted({s.stand for s in seats})
    gates = sorted({s.gate for s in seats})
    if len(sectors) <= 4:
        kinds = sorted({SECTOR_TYPE_LABEL.get(s.sector_type, s.sector_type) for s in seats} - {"Home"})
        extra = f" ({', '.join(kinds)})" if kinds else ""
        return f"{' and '.join(stands)}, sector{'s' if len(sectors) > 1 else ''} {', '.join(sectors)}{extra}; " \
               f"gate{'s' if len(gates) > 1 else ''} {', '.join(gates)}"
    return f"{len(sectors)} home sectors in {len(stands)} stands; gates {', '.join(gates)}"


def code_table(tickets: list[Ticket]) -> list[str]:
    lines = ["| Ticket | Code | Seat | Ticket image |", "|---|---|---|---|"]
    lines += [f"| {t.ticket_id} | `{t.code}` | {seat_text(t)} | {files_text(t)} |" for t in tickets]
    return lines


def render_readme(ctx: MatchContext, tickets: list[Ticket], qr_rule: str) -> str:
    by_tier = {name: [t for t in tickets if t.tier.name == name] for name in TIERS}
    samples = [t for t in tickets if t.tier.name in ("silver", "gold") and t.published]
    preview = [next(t for t in by_tier[name] if t.files) for name in ("silver", "gold", "demo")]
    lines = [
        f"# statseat tickets: {ctx.match_id}",
        "",
        f"> **Synthetic demo tickets – not valid for entry.** The match ({ctx.home.name} v {ctx.away.name}, "
        f"{ctx.match_name}), the clubs, the stadium and every person are fictional.",
        "",
        f"These are the digital tickets of the synthetic match **{ctx.match_id}**: {ctx.competition}, matchday "
        f"{ctx.matchday}, {ctx.date_text}, kick-off {ctx.time_text}, {ctx.stadium}. A ticket code unlocks **statseat**, "
        "the fan companion app of InsideTheGame, for this match only. The tier of the ticket decides what the app shows.",
        "",
        "This folder is generated by `generator/` (`python -m insidethegame_gen.tickets "
        f"{ctx.match_id}`). Do not edit it by hand.",
        "",
        '<p align="center">',
    ]
    lines += [f'  <img src="{t.files["png"]}" width="240" alt="{t.alt}">' for t in preview]
    lines += [
        "</p>",
        "",
        "## How to log in",
        "",
        "1. Open the statseat app (the demo link is in the main README of the repository).",
        "2. Type one of the codes below, or scan the QR code on a ticket image. Upper or lower case, spaces and dashes "
        "do not matter; O counts as 0, and I or L as 1.",
        "3. DEMO codes work on several devices at the same time. Silver and gold codes are bound to the first "
        "device that uses them, as a real fan's ticket would be.",
        "",
        "## What each tier unlocks",
        "",
        "| Tier | Letter | statseat mode | Inspector mode | Demo panel | Devices | Tickets | Seats |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name in ("demo", "gold", "silver"):
        t = TIERS[name]
        lines.append(f"| **{name.upper()}** | {t.letter} | {MODE_TEXT.get(t.modes, ', '.join(t.modes))} | "
                     f"{'yes' if t.inspector else 'no'} | {'yes' if t.demo_panel else 'no'} | "
                     f"{'several' if t.multi_device else 'one'} | {len(by_tier[name])} | {tier_seats(tickets, name)} |")
    lines += [
        "",
        "- **Fan**: the match explained simply, for any fan. **Analyst**: the full statistics and the method behind "
        "them.",
        "- **Inspector mode**: shows how each answer was made: the method, the agents and tools that were called, the "
        "tokens and the trace.",
        "- **Demo panel**: jumps between the phases of the match (pre-match, live, half-time, full time), so the whole "
        "app can be seen in a few minutes.",
        "",
        "## DEMO codes (Gold + Inspector + demo panel)",
        "",
        "For the hackathon judges, the demo and the video. The seats are together in the Club Level of the Main Stand.",
        "",
        *code_table(by_tier["demo"]),
        "",
        "## Sample silver and gold tickets",
        "",
        "Ordinary fans' tickets, one device each. Their codes are printed on the sample images.",
        "",
        *code_table(samples),
        "",
        f"The other {sum(1 for t in tickets if not t.published)} codes are not published: the registry keeps only "
        "their hashes.",
        "",
        "## How the codes work",
        "",
        "- **Format**: `GNT-SYN001-<tier>-XXXX-XXXX`. `GNT` is the app, `SYN001` the match, the tier letter is S "
        "(silver), G (gold) or D (demo).",
        "- **Alphabet**: the last 8 characters use Crockford base32 (digits and capital letters without I, L, O and U), "
        "so no two characters look alike.",
        "- **Check character**: the last character is computed from all the others (Luhn mod 32), so the app catches "
        "any single mistyped character before asking the server.",
        "- **Hashes only**: the registry [`tickets.json`](tickets.json) lists all "
        f"{len(tickets)} tickets with tier, features and seat, and for each code only `code_sha256`, the SHA-256 of "
        "the normalised code (upper case, with dashes). The server does the same: it hashes what the fan types and "
        "looks the hash up.",
        f"- **QR code**: it contains {qr_rule}.",
        "- **Limits**: these are demo credentials. They are derived from public inputs (the universe seed, the match "
        "id and the generator code are all in this repository), so anyone can regenerate them, and a hash of a code "
        "this short can be reversed by brute force. That is fine for a synthetic demo. In production, the ticketing "
        "system would derive the codes from a secret key kept in Azure Key Vault, and the server would store only "
        "salted hashes.",
        "- **Seats**: gates, stands and sectors come from the stadium data; rows and seat numbers are synthetic "
        "(about 80 seats per row). Home tickets never use the away section.",
        "",
        "## Files",
        "",
        "| File | Content |",
        "|---|---|",
        f"| [`tickets.json`](tickets.json) | the registry: {len(tickets)} tickets, hashes only, with an alt text for "
        "each ticket |",
        f"| `png/` | ticket images, {PNG_SIZE[0]} × {PNG_SIZE[1]} px (a phone screen) |",
        f"| `pdf/` | the same tickets as PDF, {W * 3 // 4} × {H * 3 // 4} pt |",
        f"| `svg/` | the same tickets as SVG, {W} × {H}, with a title and a description for screen readers |",
        "",
        "Rendered tickets: every DEMO ticket, plus four silver and four gold samples. Crests: the club crest "
        "from `synthetic/crests/<club_id>.svg` when it exists, otherwise a plain placeholder shield in the club's "
        "home-kit colours.",
        "",
    ]
    return "\n".join(lines)
