"""Command line: build the universe, render the Kit Man documents, validate, write.

    cd generator
    .venv/bin/python -m insidethegame_gen --seed 2026

Nothing is written if a check fails. Outputs (all synthetic, committed):
    synthetic/universe/universe.json
    synthetic/schema/{universe,match_info}.schema.json
    synthetic/<match_id>/match_info.json
    synthetic/<match_id>/kitman/*.md
    synthetic/README.md (overview)
    reports/synthetic/universe/README.md
"""

