def pass_speed_p99(repo: Path, cfg: PrepConfig) -> tuple[float, str]:
    """``R-SHOT-POWER`` threshold (km/h): the 99th percentile of DFL pass speeds from ``calibration/ball.json``
    (``pass_speed_ms.p99``) when present, else the configuration fallback."""
    p = Path(repo) / "calibration" / "ball.json"
    try:
        v = json.loads(p.read_text())["pass_speed_ms"]["p99"]
        if v is not None and np.isfinite(float(v)):
            return round(float(v) * 3.6, 2), "calibration/ball.json pass_speed_ms.p99"
    except (OSError, KeyError, TypeError, ValueError):
        pass
    return float(cfg.pass_speed_p99_kmh), "configuration fallback pass_speed_p99_kmh (calibration/ball.json has no pass_speed_ms.p99)"


def ball_height_usable(frames: pd.DataFrame) -> dict:
    """``ball_height_supplied``: the ball has a usable z (finite on most live samples and not constant)."""
    b = frames.loc[frames["is_ball"]]
    live = b.loc[b["ball_status"] == 1, "z"] if b["ball_status"].notna().any() else b["z"]
    fin = live[np.isfinite(live)]
    share = float(len(fin) / len(live)) if len(live) else 0.0
    span = float(fin.max() - fin.min()) if len(fin) else 0.0
    return {"supplied": bool(share >= 0.5 and span > 0.5), "finite_share_live": round(share, 4), "range_m": round(span, 3),
            "rule": "finite on >= 50 % of live ball samples and spanning more than 0.5 m (a constant height is not usable)"}


def coordinate_resolution(frames: pd.DataFrame, max_values: int = 200_000) -> float | None:
    """Smallest step between distinct player x values (for example 0.01 m when the provider writes 2 decimals).

    Recorded in the profile: at a coarse resolution two frozen tracks can share a value by coincidence, which
    matters when ``R-PARKING`` is supported by few players."""
    v = frames.loc[~frames["is_ball"], "x"].to_numpy()[:max_values]
    v = np.unique(np.round(v[np.isfinite(v)], 6))
    d = np.diff(v)
    d = d[d > 0]
    return round(float(d.min()), 6) if len(d) else None


def provider_arrays(frames: pd.DataFrame, ha) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Provider S (m/s), D (m), A (m/s^2) per (frame, player), plus ball S. Tests only."""
    nf, npl = ha.x.shape
    h = frames.loc[frames["half"] == ha.half]
    col = {pid: i for i, pid in enumerate(ha.object_ids)}
    p = h.loc[~h["is_ball"] & h["object_id"].astype(str).isin(col)]
    fi = (p["n"].to_numpy() - ha.n0).astype(np.int64)
    ci = p["object_id"].astype(str).map(col).to_numpy()
    out = []
    for c in ("s_ms", "d_m", "a_ms2"):
        a = np.full((nf, npl), np.nan)
        a[fi, ci] = p[c].to_numpy()
        out.append(a)
    b = h.loc[h["is_ball"]]
    bs = np.full(nf, np.nan)
    bs[(b["n"].to_numpy() - ha.n0).astype(np.int64)] = b["s_ms"].to_numpy()
    return out[0], out[1], out[2], bs


def run(match_id: str, repo: Path = REPO, cfg: PrepConfig = DEFAULT_CONFIG, log=print, use_cache: bool = True,
        write_frames: bool = True, overwrite_frames: bool = False, kloppy_check: bool = True, source: str = "dfl",
        frames_dir: Path | None = None, reports_dir: Path | None = None, acc_window_test: bool = True,
        synthetic_dir: Path | None = None) -> dict:
    """Prepare one match (guidelines v4, section 6.4). ``source``: ``"dfl"`` (``data/raw/dfl/``) or ``"synthetic"``
    (``synthetic/<match_id>/``, or the folder ``synthetic_dir``, for example a replica in ``synthetic/replicas/``).

    ``reports_dir`` overrides the folder of the per-match report folders (default ``reports/qc``; a scratch run
    writes elsewhere). ``frames_dir`` overrides where the git-ignored frame-level outputs go (default
    ``reports/qc/frames/<id>/v4``, or ``<reports_dir>/frames/<id>/v4`` with ``reports_dir``).
    ``acc_window_test``: run ``R-ACC-WINDOW-TEST`` (step 16).
    """
    if source not in ("dfl", "synthetic"):
        raise ValueError(f"unknown source {source!r} (dfl or synthetic)")
    repo = Path(repo)
    raw = repo / "data" / "raw" / "dfl"
    qc_root = Path(reports_dir) if reports_dir else repo / "reports" / "qc"
    out_dir = qc_root / match_id
    frames_dir = Path(frames_dir) if frames_dir else qc_root / "frames" / match_id / FRAMES_VERSION
    out_dir.mkdir(parents=True, exist_ok=True)
    steps: list[str] = []

    def step(msg):
        steps.append(msg)
        log(msg)

    # --- ingestion (section 2) ---
    if source == "synthetic":
        from .io_synthetic import load_synthetic_match

        folder = Path(synthetic_dir) if synthetic_dir else repo / "synthetic" / match_id
        sf, info, ev, pos, adapter_log = load_synthetic_match(folder, match_id)
        input_paths = (sf.match_info, sf.events, sf.positions)
        mf = sf
        provider = detect_format(sf.folder)["provider"]
        data_format = "InsideTheGame synthetic folder (match_info.json, events.json, positions.parquet)"
        source_text = SYNTHETIC_SOURCE
        kloppy_check = False  # kloppy has no reader for our own format
        for line in adapter_log.lines:
            step(f"adapter: {line}")
    else:
        mf = find_match_files(raw, match_id)
        input_paths = (mf.matchinformation, mf.events, mf.positions)
        info = load_matchinformation(mf.matchinformation)
        ev = load_events(mf.events)
        pos = load_positions_cached(mf.positions, repo / "data" / "interim" / "dfl" / match_id) if use_cache else load_positions(mf.positions)
        provider, data_format, source_text = None, "xml (PutDataRequest)", SOURCE
    inputs = {p.name: {"sha256": sha256(p), "bytes": p.stat().st_size, "detected": detect_format(p)} for p in input_paths}
    if provider is None:
        provider = inputs[mf.positions.name]["detected"]["provider"]
    if pos.frames.empty or pos.frames["t_utc"].isna().all():
        raise RuntimeError("stop condition (section 5.4): no time information")
    step(f"load: {len(pos.frames):,} tracking rows in {len(pos.framesets)} tracks; {ev.n_raw} events ({ev.n_delete} Delete dropped)")
    non_players = pos.framesets.loc[~pos.framesets["is_ball"] & ~pos.framesets["team_id"].astype(str).isin([info.home_team_id, info.away_team_id])]
    if len(non_players):
        step(f"objects: {non_players['object_id'].nunique()} tracked non-player objects ({sorted(non_players['team_id'].astype(str).unique())}) kept out of player preparation")

    prep_log = [log_line("R-DELETE drop Delete / placeholder events", ev.n_delete, note=f"{ev.n_raw} raw events, {ev.n_raw - ev.n_delete} kept")]
    frames, l2 = sort_rows(pos.frames)
    l2["count"] += ev.n_out_of_order_in_file
    l2["note"] = f"{l2['count'] - ev.n_out_of_order_in_file} tracking rows out of order; {ev.n_out_of_order_in_file} event pairs out of time order in the file; all sorted"
    prep_log.append(l2)
    frames, l3 = deduplicate(frames)
    prep_log.append(l3)
    irr = sampling_irregularity(frames, cfg.sampling_tolerance_frac)
    frames, l4 = resample_if_irregular(frames, {h: v["fs_hz"] for h, v in irr.items()}, cfg.sampling_tolerance_frac)
    prep_log.append(l4)
    prep_log.append(missing_samples(frames))
    pos.frames = frames

    # --- match profile (section 3) ---
    player_teams = {info.home_team_id, info.away_team_id}
    has = {int(h): build_half_arrays(frames, int(h), player_teams) for h in sorted(frames["half"].unique())}
    profile = build_match_profile(info, ev, pos, has, cfg)
    events = ev.events
    L, W = profile["pitch_length_m"], profile["pitch_width_m"]
    fs1 = float(profile["fs_hz"]["1"])
    cx, cy = profile["centre_spot_in_tracking"]
    home, away = info.home_team_id, info.away_team_id
    sign = 1.0 if profile["direction_per_half"]["1"]["home_attacks_positive_x"] else -1.0
    units = infer_coordinate_units(frames["x"].to_numpy(), frames["y"].to_numpy())
    prov_peak = float(frames.loc[~frames["is_ball"], "s_ms"].max() * 3.6) if frames["s_ms"].notna().any() else float("nan")
    prov_units = infer_speed_units(prov_peak)
    prep_log.append(log_line("R-UNITS timezones and units", sum(1 for t in profile["timezones"]["events"] if t != "+00:00"),
                             note=f"events {profile['timezones']['events']} and tracking {profile['timezones']['tracking']} converted to UTC; "
                                  f"coordinates inferred as {units['units']} (span {units['span']:.1f}); provider S peak {prov_peak:.1f} inferred as {prov_units['units']}"))

    lineup = english_lineup(info.lineup)
    unmapped = lineup.loc[lineup["unmapped"], "playing_position"].fillna("NONE").value_counts().to_dict()
    formations = {r: map_formation(v) for r, v in info.formations.items()}
    etc = event_type_counts(events["event_type"])  # R-MAP-EN (v4.2): event types, including those outside the DFL 23-type list
    prep_log.append(log_line("R-MAP-EN provider / German codes to English", int(lineup["playing_position"].notna().sum()) + len(formations),
                             [f"{c} -> {r}" for c, r in lineup.dropna(subset=["playing_position"])[["playing_position", "role"]].drop_duplicates().head(3).itertuples(index=False)],
                             note=f"{int(lineup['playing_position'].notna().sum())} playing positions and {len(formations)} formations mapped; unmapped: {unmapped or 'none'} (players without a position code are unused substitutes); shot outcomes mapped with section 16.3; "
                                  f"{len(events)} events of {len(etc['by_type'])} types mapped (section 16.4), outside the DFL 23-type list: {etc['outside_dfl_list'] or 'none'}, unmapped event types: {etc['unmapped'] or 'none'}"))

    # --- canonical arrays (section 4): centre origin, home attacks +x in period 1 ---
    role = {home: "home", away: "away"}
    hds: dict[int, HalfData] = {}
    for h, ha in has.items():
        s, d, a, bs = provider_arrays(frames, ha)
        fs = float(profile["fs_hz"][str(h)])
        hds[h] = HalfData(half=h, fs=fs, n=ha.n, t_s=ha.t_s, pids=ha.object_ids, team_side=[role.get(t, "unknown") for t in ha.team_ids],
                          x=sign * (ha.x - cx), y=sign * (ha.y - cy), prov_s=s, prov_d=d, prov_a=a,
                          bx=sign * (ha.ball_x - cx), by=sign * (ha.ball_y - cy), bz=ha.ball_z, bstatus=ha.ball_status, bposs=ha.ball_possession, ball_prov_s=bs)
    height = ball_height_usable(frames)

    # --- time alignment (section 9.1, 9.3 step 1) ---
    half_t = {h: hd.t_s for h, hd in hds.items()}
    half_st = {h: hd.bstatus for h, hd in hds.items()}
    kick = period_kickoffs(events, half_t, half_st, {h: (hd.bx, hd.by) for h, hd in hds.items()}, info.kickoff_time_utc, cfg)
    offsets = event_clock_offset(events, half_t, half_st, cfg)

    # --- substitutions (event time corrected by the period's clock offset) ---
    subs_by_half: dict[int, list] = {}
    for s in profile["substitutions"]:
        h = int(s["half"])
        t_ev = pd.Timestamp(s["time_utc"]).timestamp() + offsets[h]["event_clock_offset_s"]
        subs_by_half.setdefault(h, []).append({**s, "event_time_s": t_ev})

    # --- R-EDGE then R-PARKING, on the whole match (section 5.2). Substitutions with identity inheritance link the
    # incoming ID to the outgoing player's track, so an inherited frozen position is one track, not two players. ---
    edges = discover_edges([hd.x for hd in hds.values()], [hd.y for hd in hds.values()], L / 2, W / 2, cfg.edge_min_samples, cfg.edge_value_decimals)
    links = {}
    for h, hd in hds.items():
        links.update(inheritance_links(list(hd.pids), hd.x, hd.y, subs_by_half.get(h, []), cfg))
    parking = discover_parking_values([hd.x for hd in hds.values()], [hd.y for hd in hds.values()], [list(hd.pids) for hd in hds.values()], L / 2, W / 2,
                                      cfg.frames(cfg.frozen_min_s, fs1), cfg.parking_min_samples, cfg.parking_min_tracks, edges["edges"], cfg.edge_value_decimals,
                                      same_track=links)
    step(f"edges: {[(e['axis'], e['value_m'], e['samples']) for e in edges['edges']]}; parking values: {[(v['axis'], v['value_m'], v['players']) for v in parking['parking_values']]}")

    # --- preparation per period (section 6.4, steps 3-13) ---
    pairs = []
    for h, hd in hds.items():
        hr = prepare_half(hd, subs_by_half.get(h, []), edges["edges"], (L, W), cfg, parking=parking["parking_values"])
        pairs.append((hd, hr))
        step(f"period {h}: valid {hr.valid.sum() / hr.present.sum():.4f} of player samples; ball valid {hr.ball_valid.sum():,}")

    # Substitution frame-set switch times (for event location).
    switch = first_appearance_times([(hd.half, hd.pids, hd.t_s, hr.present) for hd, hr in pairs])
    events_located = locate_events(events, half_t, {h: hd.n for h, hd in hds.items()}, half_st, offsets, switch, cfg)

    # --- goals, passes, shots, clearances, duels located from trajectories (section 9.3 steps 3-7) ---
    group_of = dict(zip(lineup["person_id"], lineup["role_group"]))
    sync_periods = {}
    for hd, hr in pairs:
        raw_home_pos = bool(profile["direction_per_half"][str(hd.half)]["home_attacks_positive_x"])
        px, py = hr.x_est.copy(), hr.y_est.copy()
        px[hr.discarded | ~hr.present], py[hr.discarded | ~hr.present] = np.nan, np.nan  # positions that are not real are never used
        ball_pos_ok = ~np.isin(hr.ball_reason, [CODE["jump"], CODE["limit"]])
        sync_periods[hd.half] = SyncPeriod(half=hd.half, fs=hd.fs, n=hd.n, t_s=hd.t_s, pids=hd.pids, team_side=hd.team_side, px=px, py=py,
                                           bx=hd.bx, by=hd.by, bz=hd.bz if height["supplied"] else np.full(len(hd.n), np.nan), bstatus=hd.bstatus,
                                           home_attack_sign=sign * (1.0 if raw_home_pos else -1.0),
                                           ball_speed=np.where(hr.ball_valid, hr.ball_speed, np.nan), ball_valid=hr.ball_valid, ball_pos_ok=ball_pos_ok,
                                           role_group=[group_of.get(p) for p in hd.pids])
    gk_ids = set(lineup.loc[lineup["role_group"] == "GK", "person_id"])
    p99_kmh, p99_source = pass_speed_p99(repo, cfg)
    events_located = locate_play_events(events_located, sync_periods, offsets, gk_ids, role, L, cfg, pass_p99_kmh=p99_kmh)
    goal_rows = events_located.attrs.get("goal_crossings", [])
    # R-HIGHLIGHT (section 9.11): goals, woodwork and saves, anchored on the outcome and walked back to the action's start.
    hl_anchors = [{"kind": "goal", "index": r["index"], "attack_side": r["attacking_side"], "period": r["period"]}
                  for r in goal_rows if r["goal_check"] == "goal"]
    for _, r in events_located.loc[events_located["event_kind"] == "shot"].iterrows():
        if r["shot_outcome_observed"] in ("saved", "woodwork") and pd.notna(r["sync_frame"]):
            h = int(r["half"])
            hl_anchors.append({"kind": "save" if r["shot_outcome_observed"] == "saved" else "woodwork", "index": int(r["sync_frame"]) - int(hds[h].n[0]),
                               "attack_side": r["acting_team_side"], "period": h})
    highlight_rows = []
    for h, hd in hds.items():
        mine = [a for a in hl_anchors if a["period"] == h and a["attack_side"] in ("home", "away")]
        bposs_h = np.where(hd.bposs == 1, 1, np.where(hd.bposs == 2, 2, 0))
        highlight_rows += [dict(x, period=h) for x in make_highlights(mine, hd.bstatus, bposs_h, float(profile["fs_hz"][str(h)]), cfg)]
    step(f"events located: {events_located['sync_method'].value_counts().to_dict()}; goal crossings: {[r['goal_check'] for r in goal_rows]}")

    # --- summaries ---
    summary = player_summary(pairs, lineup, cfg)
    reason_counts: dict[str, int] = {}
    ball_counts: dict[str, int] = {}
    total_player, total_ball = 0, 0
    for hd, hr in pairs:
        for k, v in summarise_reasons(hr.reason, hr.present).items():
            reason_counts[k] = reason_counts.get(k, 0) + v
        bp = np.isfinite(hd.bx)
        for k, v in summarise_reasons(hr.ball_reason, bp).items():
            ball_counts[k] = ball_counts.get(k, 0) + v
        total_player += int(hr.present.sum())
        total_ball += int(bp.sum())
    reason_counts = {r: reason_counts.get(r, 0) for r in REASONS if r in reason_counts}
    est = sum(int(hr.estimated.sum()) for _, hr in pairs)
    disc = sum(int(hr.discarded.sum()) for _, hr in pairs)

    # Catalogue (frame-level CSV is git-ignored) and aggregates.
    cat_rows = []
    t_of = {}
    for hd, hr in pairs:
        for r in hr.catalogue:
            i = r["index"]
            t_of[(hd.half, int(hd.n[i]))] = float(hd.t_s[i])
            cat_rows.append({**{k: v for k, v in r.items() if k not in ("index", "col", "partner_col")},
                             "frame_N": int(hd.n[i]), "match_clock_s": round(float(hd.t_s[i] - kick[hd.half]["kickoff_s"]), 2),
                             "object_id": "BALL" if r["col"] < 0 else hd.pids[r["col"]],
                             "team_side": "none" if r["col"] < 0 else hd.team_side[r["col"]],
                             "partner_id": hd.pids[r["partner_col"]] if "partner_col" in r else None,
                             "ball_status": "live" if hd.bstatus[i] == 1 else "dead"})
    cat = pd.DataFrame(cat_rows)
    if not cat.empty:
        cat = cat.sort_values(["half", "frame_N", "object_id", "anomaly_type"], kind="mergesort").reset_index(drop=True)
    # R-JUMP-CONTEXT: provider events within +-2 s of every unknown jump (never changes the exclusion).
    cat, jump_ctx = annotate_unknown_jumps(cat, events, offsets, t_of, role, cfg)

    # Gap, edge, parking, frozen, swap, substitution aggregates.
    gaps = [g | {"half": hd.half, "object_id": hd.pids[g["col"]]} for hd, hr in pairs for g in hr.gaps]
    gap_cols = ["col", "lo", "hi", "frames", "pinned", "parked", "resume_m", "kind", "handling", "method", "estimated_distance_m", "half", "object_id"]
    gdf = pd.DataFrame(gaps).reindex(columns=gap_cols) if gaps else pd.DataFrame(columns=gap_cols)
    frozen_runs = int(((gdf["kind"].isin(["frozen", "reentry", "exit", "track_head"])) & ~gdf["pinned"].astype(bool) & ~gdf["parked"].astype(bool)).sum()) if len(gdf) else 0
    edge_runs = [er | {"half": hd.half, "object_id": hd.pids[er["col"]]} for hd, hr in pairs for er in hr.edge_runs]
    parked_runs = [pr | {"half": hd.half, "object_id": hd.pids[pr["col"]]} for hd, hr in pairs for pr in hr.parked_runs]
    edge_live = 0
    for hd, hr in pairs:
        for er in hr.edge_runs:
            edge_live += int((hd.bstatus[er["lo"]:er["hi"] + 1] == 1).sum())
    swaps = [s | {"half": hd.half} for hd, hr in pairs for s in hr.swaps]
    subs = [s | {"half": hd.half} for hd, hr in pairs for s in hr.substitutions]
    jumps = cat.loc[cat["anomaly_type"] == "jump"] if len(cat) else pd.DataFrame()
    ball_logs = {hd.half: hr.log["ball"] for hd, hr in pairs}

    # R-ACC-BAND aggregates (never an exclusion).
    band = {cls: {sign_: {k: sum(hr.log["acc_band"][cls][sign_][k] for _, hr in pairs) for k in ("runs", "samples")}
                  for sign_ in ("acceleration", "deceleration")} for cls in ("noise", "approx")}
    band_examples = sorted(({"half": hd.half, "object_id": hd.pids[r["col"]], "frame_N": int(hd.n[r["lo"]]), "samples": r["samples"], "class": r["class"],
                             "sign": r["sign"], "peak_ms2": round(r["peak"], 2)} for hd, hr in pairs for r in hr.acc_band if r["class"] == "approx"),
                           key=lambda r: (-abs(r["peak_ms2"]), r["half"], r["frame_N"]))[:10]

    def gap_stats(kind=None):
        g = gdf if kind is None else gdf.loc[gdf["kind"] == kind]
        if g.empty:
            return {"runs": 0}
        return {"runs": int(len(g)), "samples": int(g["frames"].sum()), "estimated_runs": int((g["handling"] == "estimated").sum()),
                "discarded_runs": int((g["handling"] == "discarded").sum()),
                "methods": g.loc[g["handling"] == "estimated", "method"].value_counts().to_dict() if "method" in g else {},
                "resume_m_median": float(g["resume_m"].median()) if g["resume_m"].notna().any() else None}

    jumps_by = (lambda r: int((jumps["exclusion_reason"] == r).sum()) if len(jumps) else 0)
    prep_log += [
        log_line("R-BALL-DEAD, R-BALL-WINDOW ball while dead and ball windows", sum(b["dead_samples"] for b in ball_logs.values()),
                 note=f"ball kinematics invalid while dead and for {cfg.ball_restart_s:g} s after each of the {sum(b['restarts'] for b in ball_logs.values())} dead->live restarts; "
                      f"+-{cfg.ball_window_s:g} s around live-play ball jumps and limit violations; "
                      f"{sum(b['restart_jumps_ignored'] for b in ball_logs.values())} position jumps at restarts ignored"),
        log_line("R-EDGE tracking-area edges", int(sum(er["hi"] - er["lo"] + 1 for er in edge_runs)),
                 [f"{er['object_id']} P{er['half']} {(er['hi'] - er['lo'] + 1) / fs1:.1f} s" for er in edge_runs],
                 note=f"{len(edge_runs)} runs from {len({er['object_id'] for er in edge_runs})} players at {[e['axis'] + '=' + format(e['value_m'], 'g') for e in edges['edges']] or 'no edge'}; "
                      f"{edge_live} of these samples in live play; outside_tracking_area with +-1 s"),
        log_line("R-PARKING parking values on frozen tracks", int(sum(pr["hi"] - pr["lo"] + 1 for pr in parked_runs)),
                 [f"{pr['object_id']} P{pr['half']} {(pr['hi'] - pr['lo'] + 1) / fs1:.1f} s" for pr in parked_runs],
                 note=f"{len(parked_runs)} parked runs from {len({pr['object_id'] for pr in parked_runs})} players at "
                      f"{[v['axis'] + '=' + format(v['value_m'], 'g') + ' (' + str(v['players']) + ' players)' for v in parking['parking_values']] or 'no parking value'}; "
                      "parked (first sample included) with +-1 s"),
        log_line("R-FROZEN frozen tracks (>= 1 s)", frozen_runs, note=f"frozen runs not at an edge or a parking value: {gap_stats('frozen')}"),
        log_line("R-JUMP position jumps", int(len(jumps)), note=f"players: steps > {cfg.player_speed_max_ms / fs1:.3f} m at {fs1:g} Hz in every phase, +-1 s window; "
                                                               f"ball: {sum(b['live_jump_episodes'] for b in ball_logs.values())} live-play jump episodes, +-{cfg.ball_window_s:g} s"),
        log_line("R-SWAP, R-SWAP-RESTORE identity swaps", len(swaps), note=f"{sum(s['corrected'] for s in swaps)} mutual swaps followed by their correction within {cfg.swap_pair_max_s:g} s -> labels swapped back; "
                                                                           f"{sum(not s['corrected'] for s in swaps)} not corrected in time (window only); {jumps_by('swap')} jump episodes windowed as swaps"),
        log_line("R-SUB-INHERIT substitutions (identity inheritance)", len(subs),
                 note=f"{sum(1 for s in subs if s.get('inheritance'))} of {len(subs)} incoming tracks inherit the outgoing player's last position (< {cfg.sub_inherit_max_m:g} m, <= 1 frame); "
                      f"{sum(1 for s in subs if s.get('reacquisition_jump'))} with a re-acquisition jump (invalid until the jump + {cfg.sub_stabilisation_s:g} s); "
                      f"the others are invalid for their first {cfg.sub_no_jump_invalid_s:g} s only"),
        log_line("R-EXIT-REENTRY exit / re-entry", int(len(gdf.loc[gdf['kind'].isin(['exit', 'reentry'])])) if len(gdf) else 0,
                 note=f"exits {gap_stats('exit').get('runs', 0)}, re-entries {gap_stats('reentry').get('runs', 0)}"),
        log_line("R-OVERLAP-CROWD crowding / overlaps", jumps_by("crowding") + sum(hr.log["overlaps"] for _, hr in pairs),
                 note=f"{jumps_by('crowding')} jump episodes in crowding; {sum(hr.log['overlaps'] for _, hr in pairs)} overlap episodes (< 0.3 m for >= 0.2 s)"),
        log_line("R-SPEED-LIMIT, R-BALL-LIMIT physical limits", sum(hr.log["limit_new_episodes"] for _, hr in pairs),
                 note=f"player episodes beyond {cfg.player_speed_max_kmh:g} km/h not already inside another window; ball live > {cfg.ball_speed_max_kmh:g} km/h: "
                      f"{sum(b['limit_episodes'] for b in ball_logs.values())}"),
        log_line("R-ACC-BAND acceleration band (never an exclusion)", sum(band[c][s_]["runs"] for c in band for s_ in band[c]),
                 note=f"noise (<= {cfg.acc_noise_max_s:g} s): {band['noise']['acceleration']['runs']} acceleration and {band['noise']['deceleration']['runs']} deceleration runs "
                      f"({band['noise']['acceleration']['samples'] + band['noise']['deceleration']['samples']} samples, acceleration not used); "
                      f"approx (> {cfg.acc_noise_max_s:g} s): {band['approx']['acceleration']['runs']} + {band['approx']['deceleration']['runs']} runs "
                      f"({band['approx']['acceleration']['samples'] + band['approx']['deceleration']['samples']} samples, reported with '≈')"),
        log_line("R-UNKNOWN, R-JUMP-CONTEXT unknown anomalies", jumps_by("unknown"),
                 note=f"jump episodes with no signature, excluded +-1 s whatever the cause ({jump_ctx.get('in_live_play', 0)} in live play, {jump_ctx.get('in_dead_ball', 0)} in dead ball; "
                      f"{jump_ctx.get('with_events_within_window', 0)} with a provider event within +-{cfg.jump_context_s:g} s); "
                      f"plus {sum(hr.log['short_segment_samples'] for _, hr in pairs)} samples in segments shorter than the filter window"),
        log_line("R-TRACK-START first moments not tracked", len(kick), note="; ".join(f"P{h}: tracking starts {v['tracking_start_offset_s']:+.2f} s after kickoff" for h, v in kick.items())),
    ]
    step("preparation log: " + ", ".join(f"{p['rule'].split()[0]}={p['count']}" for p in prep_log))

    # --- additions to the match profile ---
    lived = {h: float(np.sum(hd.bstatus == 1) / hd.fs) for h, hd in hds.items()}
    for h, v in profile["playing_time"].items():
        v["ball_live_s"] = lived.get(int(h))
    role_evidence = []
    first = pairs[0]
    hd1, hr1 = first
    for c, pid in enumerate(hd1.pids):
        m = hr1.valid[:, c]
        if m.sum() < fs1 * 60:
            continue
        s_att = 1.0 if hd1.team_side[c] == "home" else -1.0  # canonical: home attacks +x in period 1
        row = lineup.loc[lineup["person_id"] == pid].iloc[0]
        role_evidence.append({"object_id": pid, "team_side": hd1.team_side[c], "source_code": row["playing_position"], "role": row["role"],
                              "role_group": row["role_group"], "mean_x_att": float(np.mean(s_att * hr1.x[m, c])), "mean_y_att": float(np.mean(s_att * hr1.y[m, c]))})
    profile.update({
        "guidelines_version": cfg.guidelines_version,
        "provider": provider,
        "format": data_format,
        "units": {"coordinates": units, "provider_speed": prov_units, "provider_step": "cm (D), converted to m", "provider_acceleration": "m/s2 (A)"},
        "canonical_transform": {"x_canonical": f"{sign:+.0f} * (x_tracking - {cx})", "y_canonical": f"{sign:+.0f} * (y_tracking - {cy})",
                                "rotation_deg": 0 if sign > 0 else 180,
                                "reason": "home attacks +x in period 1 after normalisation" + ("" if sign > 0 else " (raw: home attacks -x in period 1)")},
        "event_to_canonical_transform": {"x_canonical": f"{sign * profile['event_to_tracking_transform']['best']['sx']:+.0f} * (x_event - {profile['centre_spot_in_events'][0]})",
                                         "y_canonical": f"{sign * profile['event_to_tracking_transform']['best']['sy']:+.0f} * (y_event - {profile['centre_spot_in_events'][1]})"},
        "kickoff_per_period": {str(h): {k: v for k, v in d.items() if k != "kickoff_s"} for h, d in kick.items()},
        "tracking_area_edges": edges,
        "parking_values": parking,
        "coordinate_resolution_m": coordinate_resolution(frames),
        "event_clock_offset": {str(h): v for h, v in offsets.items()},
        "provider_kinematics_supplied": {"speed_S": bool(frames["s_ms"].notna().any()), "acceleration_A": bool(frames["a_ms2"].notna().any()),
                                         "step_D": bool(frames["d_m"].notna().any()), "use": "tests only"},
        "ball_status_supplied": bool(frames.loc[frames["is_ball"], "ball_status"].notna().any()),
        "ball_possession_supplied": bool(frames.loc[frames["is_ball"], "ball_possession"].notna().any()),
        "ball_height_supplied": height["supplied"],
        "ball_height": height,
        "formations": formations,
        "venue_country": map_value(info.country) if (info.country or source == "dfl") else "not supplied",
        "lineup_roles": lineup[["person_id", "team_role", "starting", "playing_position", "role", "role_group"]].rename(columns={"playing_position": "source_code"}).to_dict(orient="records"),
        "role_evidence_period1": role_evidence,
        "unmapped_codes": unmapped,
        "event_types": etc,  # R-MAP-EN (v4.2), section 16.4
    })
    profile.pop("goalkeepers", None)

    # --- event location summary ---
    loc = events_located
    play = summarise_sync(loc, cfg)
    sync = {"by_method": loc["sync_method"].value_counts().to_dict(),
            "certainty_quantiles": loc["sync_certainty"].dropna().quantile([0.1, 0.5, 0.9]).round(3).to_dict() if loc["sync_certainty"].notna().any() else {},
            "restart_residual_abs_s_median": float(loc.loc[loc["sync_method"] == "dead_live_transition", "sync_residual_s"].abs().median()) if (loc["sync_method"] == "dead_live_transition").any() else None,
            "substitution_switch_minus_event_s": loc.loc[loc["sync_method"] == "frameset_switch", "sync_residual_s"].tolist(),
            "type_check": loc["type_check"].value_counts().to_dict(),
            "play_events": play,
            "shot_power_threshold": {"kmh": p99_kmh, "source": p99_source},
            "ball_height_used": bool(height["supplied"]),
            "provider_sync_comparison": provider_sync_comparison(loc, fs1)}

    prov = provider_comparison(pairs)
    bsp = np.concatenate([np.where(hr.ball_valid, hr.ball_speed, np.nan) for _, hr in pairs])
    psp = np.concatenate([np.where(hr.valid, hr.speed, np.nan).ravel() for _, hr in pairs])
    pac = np.concatenate([np.where(hr.valid & (hr.acc_status != ACC_CODE["noise"]), hr.acc_tan, np.nan).ravel() for _, hr in pairs])
    lim = cat.loc[cat["anomaly_type"] == "limit"] if len(cat) else pd.DataFrame(columns=["value"])
    peaks = {"player_speed_max_kmh": float(np.nanmax(psp) * 3.6), "player_speed_p99_9_kmh": float(np.nanquantile(psp, 0.999) * 3.6),
             "player_acc_tan_min_ms2": float(np.nanmin(pac)) if np.isfinite(pac).any() else None,
             "player_acc_tan_max_ms2": float(np.nanmax(pac)) if np.isfinite(pac).any() else None,
             "player_acc_tan_p0_1_p99_9_ms2": [float(np.nanquantile(pac, 0.001)), float(np.nanquantile(pac, 0.999))] if np.isfinite(pac).any() else [None, None],
             "acc_note": "valid samples with acc_status measured or approx (noise samples are never used)",
             "ball_live_speed_max_kmh": float(np.nanmax(bsp) * 3.6) if np.isfinite(bsp).any() else None,
             "ball_live_speed_p99_9_kmh": float(np.nanquantile(bsp, 0.999) * 3.6) if np.isfinite(bsp).any() else None,
             "limit_episodes_by_kind": lim["cause_detail"].value_counts().to_dict() if len(lim) else {}}
    kl = None
    if kloppy_check:
        from .crosscheck import kloppy_crosscheck

        kl = kloppy_crosscheck(mf)
        kl.pop("seconds", None)

    # --- R-ACC-WINDOW-TEST (step 16) ---
    awt = acc_window_sensitivity(pairs, cfg) if acc_window_test else {"available": False, "note": "skipped (--no-acc-window-test)"}

    results = {
        "match_id": match_id,
        "guidelines_version": cfg.guidelines_version,
        "pipeline_version": __version__,
        "source": source_text,
        "input_files": inputs,
        "config": cfg.to_dict() | {"savgol_window_samples": cfg.savgol_window(fs1), "acc_window_samples": cfg.acc_window(fs1)},
        "config_hash": cfg.hash(),
        "library_versions": library_versions(),
        "preparation_log": prep_log,
        "mask_summary": {
            "player_samples": total_player, "player_valid": sum(int(hr.valid.sum()) for _, hr in pairs),
            "player_by_reason": reason_counts, "player_estimated": est, "player_discarded": disc,
            "ball_samples": total_ball, "ball_valid": sum(int(hr.ball_valid.sum()) for _, hr in pairs), "ball_by_reason": ball_counts,
            "ball_log": ball_logs,
        },
        "gaps": {"all": gap_stats(), "frozen": gap_stats("frozen"), "outside_tracking_area": gap_stats("outside_tracking_area"), "parked": gap_stats("parked"),
                 "reentry": gap_stats("reentry"), "exit": gap_stats("exit"), "track_head": gap_stats("track_head"), "missing": gap_stats("missing"),
                 "estimated_distance_m": float(gdf["estimated_distance_m"].sum()) if "estimated_distance_m" in gdf else 0.0},
        "edge_runs": [{k: v for k, v in er.items() if k != "col"} | {"duration_s": round((er["hi"] - er["lo"] + 1) / fs1, 2)} for er in edge_runs],
        "parked_runs": [{k: v for k, v in pr.items() if k != "col"} | {"duration_s": round((pr["hi"] - pr["lo"] + 1) / fs1, 2)} for pr in parked_runs],
        "parking_values": parking["parking_values"],
        "highlights": highlight_rows,
        "coordinate_resolution_m": profile["coordinate_resolution_m"],
        "swaps": swaps,
        "substitutions": subs,
        "acc_band": {"by_class_and_sign": band, "approx_examples": band_examples,
                     "acc_none_valid_samples": sum(hr.log["acc_none_valid_samples"] for _, hr in pairs)},
        "acc_window_sensitivity": awt,
        "players": summary.drop(columns=[c for c in ("fs", "top_speed_index") if c in summary]).to_dict(orient="records"),
        "time_alignment": {"kickoffs": profile["kickoff_per_period"], "event_clock_offset": profile["event_clock_offset"], "event_location": sync},
        "shot_statistics": shot_statistics(events, role, cfg),
        "catalogue": {
            "episodes": int(len(cat)),
            "by_type_and_cause": cat.groupby(["anomaly_type", "suspected_cause"]).size().rename("n").reset_index().to_dict(orient="records") if len(cat) else [],
            "by_exclusion_reason": cat["exclusion_reason"].value_counts().to_dict() if len(cat) else {},
            "jumps": {"episodes": int(len(jumps)), "players": int(jumps["object_id"].nunique()) if len(jumps) else 0,
                      "median_m": float(jumps["value"].median()) if len(jumps) else None, "max_m": float(jumps["value"].max()) if len(jumps) else None,
                      "in_dead_ball": int((jumps["ball_status"] == "dead").sum()) if len(jumps) else 0},
            "unknown_jump_context": jump_ctx,
            "unknown_examples": cat.loc[cat["suspected_cause"] == "unknown"].sort_values(["value", "half", "frame_N"], ascending=[False, True, True], kind="mergesort")
                                   .head(5)[["half", "frame_N", "match_clock_s", "object_id", "team_side", "anomaly_type", "value", "ball_status", "cause_detail"]].to_dict(orient="records") if len(cat) else [],
        },
        "valid_peaks": peaks,
        "provider_comparison": prov,
        "kloppy_crosscheck": kl,
        "step_log": steps,
    }

    # R-ANON-LABELS (v4.2): for real data the committable files name people by anonymous labels ("home CB 1"); the
    # label <-> ID table goes only to the git-ignored frame-level folder. Synthetic matches keep their fictional IDs.
    amap: dict[str, str] = {}
    profile_out, results_out, players_out = profile, results, summary
    if source != "synthetic":
        labels = build_labels(lineup, {str(r.object_id): str(r.team_id) for r in non_players.drop_duplicates("object_id").itertuples(index=False)})
        amap = id_map(labels)
        profile_out, results_out, players_out = anonymise(profile, amap), anonymise(results, amap), anonymise(summary, amap)
        lab_path = qc_root / "frames" / match_id / ID_LABELS_FILE
        if lab_path.exists() and not overwrite_frames:
            step(f"frame-level file kept (not overwritten): {lab_path.relative_to(repo) if lab_path.is_relative_to(repo) else lab_path}")
        else:
            write_id_labels(lab_path, match_id, labels)
    (out_dir / "match_profile.json").write_text(dumps(profile_out))
    (out_dir / "qc_results.json").write_text(dumps(results_out))
    if awt.get("available"):
        awt_out = results_out["acc_window_sensitivity"]
        sensitivity_table(awt_out).to_csv(out_dir / "acc_window_sensitivity.csv", index=False)
        (out_dir / "acc_window_sensitivity.md").write_text(sensitivity_markdown(awt_out, match_id))

    if write_frames:
        frames_dir.mkdir(parents=True, exist_ok=True)
        targets = {"anomaly_catalogue.csv": lambda p: cat.to_csv(p, index=False),
                   "tracking_canonical.parquet": lambda p: pd.concat([to_frame(hr, hd) for hd, hr in pairs], ignore_index=True).assign(match_id=match_id).to_parquet(p, index=False),
                   "events_canonical.csv": lambda p: events_located.drop(columns=["file_order"]).to_csv(p, index=False),
                   "goal_crossings.csv": lambda p: pd.DataFrame(goal_rows).assign(match_id=match_id).to_csv(p, index=False)}
        for name, writer in targets.items():
            p = frames_dir / name
            if p.exists() and not overwrite_frames:
                step(f"frame-level file kept (not overwritten): {p.relative_to(repo) if p.is_relative_to(repo) else p}")
                continue
            writer(p)

    from .report import write_report

    write_report(out_dir / "README.md", profile_out, results_out, players_out, cfg, source=source, id_map=amap)
    step(f"report written: {(out_dir / 'README.md').relative_to(repo) if (out_dir / 'README.md').is_relative_to(repo) else out_dir / 'README.md'}")
    return results_out


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description="Prepare one match (guidelines v4) and write its preparation report.")
    ap.add_argument("match_id", help="DFL match id suffix (e.g. J03WPY) or synthetic match id (e.g. SYN-001)")
    ap.add_argument("--source", choices=("dfl", "synthetic"), default="dfl",
                    help="dfl: the three XML files in data/raw/dfl/; synthetic: the folder synthetic/<match_id>/")
    ap.add_argument("--repo", type=Path, default=REPO)
    ap.add_argument("--no-frames", action="store_true", help="do not write the git-ignored frame-level outputs")
    ap.add_argument("--reports-dir", type=Path, default=None, help="folder of the per-match report folders (default reports/qc; use a scratch folder for trial runs)")
    ap.add_argument("--frames-dir", type=Path, default=None, help=f"folder for the frame-level outputs (default <reports-dir>/frames/<id>/{FRAMES_VERSION}; keep it git-ignored)")
    ap.add_argument("--no-acc-window-test", action="store_true", help="skip the acceleration window sensitivity test (R-ACC-WINDOW-TEST)")
    ap.add_argument("--overwrite-frames", action="store_true", help="overwrite existing frame-level outputs (ask the team first)")
    ap.add_argument("--no-kloppy", action="store_true", help="skip the independent kloppy parser cross-check")
    ap.add_argument("--synthetic-dir", type=Path, default=None,
                    help="with --source synthetic: the match folder (default synthetic/<match_id>/; e.g. synthetic/replicas/SYN-001-r1)")
    a = ap.parse_args(argv)
    if a.synthetic_dir is not None and a.source != "synthetic":
        ap.error("--synthetic-dir needs --source synthetic")
    run(a.match_id, a.repo, write_frames=not a.no_frames, overwrite_frames=a.overwrite_frames, kloppy_check=not a.no_kloppy,
        source=a.source, frames_dir=a.frames_dir, reports_dir=a.reports_dir, acc_window_test=not a.no_acc_window_test,
        synthetic_dir=a.synthetic_dir)


if __name__ == "__main__":
    main()
