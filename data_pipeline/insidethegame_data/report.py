def review_list(res: dict) -> list[str]:
    """The short "to review" list: what a person should look at first (aggregates and event IDs only)."""
    pe = res["time_alignment"]["event_location"]["play_events"]
    g = pe["goals"]
    out = []
    for c in g["crossings"]:
        if c["goal_check"] in ("unconfirmed", "disallowed_goal", "pending"):
            out.append(f"`R-GOAL` P{c['period']} goal crossing ({c['attacking_side']}) is **{c['goal_check']}** (next restart: {c['next_restart_type'] or 'none'}; shot event {c['shot_event_id'] or 'not matched'}"
                       + (f"; disallowed for {c['disallowed_reason']}, `GoalDisallowed` {c['goal_disallowed_event_id']}" if c.get("disallowed_reason") else "") + ").")
        elif c["goal_check"] == "goal" and c.get("own_goal"):
            out.append(f"`R-GOAL` P{c['period']} goal ({c['attacking_side']}) attributed as an **own goal** of {c.get('scorer_id')}: the shot was not going on target before the deflection (event {c['shot_event_id'] or 'not matched'}).")
        elif c["goal_check"] == "goal" and c["kick_frame"] is None:
            out.append(f"`R-GOAL` P{c['period']} goal ({c['attacking_side']}) without a located shot (own goal or no attacking kick found).")
        elif c["goal_check"] == "goal" and c["shooter_mismatch"]:
            out.append(f"`R-GOAL` P{c['period']} goal ({c['attacking_side']}): located kicker differs from the annotated scorer (event {c['shot_event_id']}).")
        elif c["goal_check"] == "goal" and not c["shot_event_id"]:
            out.append(f"`R-GOAL` P{c['period']} goal crossing ({c['attacking_side']}) followed by a kickoff but no annotated goal shot matched.")
    if g["annotated_goals_without_goal_crossing"]:
        out.append(f"`R-GOAL` annotated goals without a confirmed goal crossing: {', '.join(g['annotated_goals_without_goal_crossing'])}.")
    nc = [s for s in pe["shots"]["rows"] if s["type_check"] == "not_confirmed"]
    if nc:
        out.append(f"`R-SHOT-CHECK` {len(nc)} shots not confirmed (listed in section 5.2): " + "; ".join(f"{s['event_id']} ({s['reason']})" for s in nc[:8]) + ("; ..." if len(nc) > 8 else "") + ".")
    cl = pe["clearances"]
    if cl["not_confirmed"]:
        out.append(f"`R-CLEARANCE` {cl['not_confirmed']} of {cl['annotated']} clearances not confirmed (clearances by conditions met: {score_text(cl['score_distribution'])}).")
    p = pe["passes"]
    unloc = p["annotated"] - p["confirmed"]
    if unloc:
        out.append(f"`R-PASS-KICK` {unloc} of {p['annotated']} passes not located (not confirmed).")
    ab = res["acc_band"]["by_class_and_sign"]
    n_approx = ab["approx"]["acceleration"]["runs"] + ab["approx"]["deceleration"]["runs"]
    if n_approx:
        out.append(f"`R-ACC-BAND` {n_approx} acceleration runs beyond the band for more than 0.2 s (reported with '≈'; examples in section 4).")
    jc = res["catalogue"].get("unknown_jump_context", {})
    if jc.get("unknown_jumps"):
        out.append(f"`R-JUMP-CONTEXT` {jc['unknown_jumps']} unknown jumps ({jc['in_live_play']} live, {jc['in_dead_ball']} dead ball); "
                   f"{jc['with_events_within_window']} have a provider event within +-{jc['window_s']:g} s (types: {_kv(dict(list(jc['event_types_nearby'].items())[:5]))}).")
    pv = res.get("parked_runs", [])
    vals = res.get("parking_values", [])
    if vals:
        few = [v for v in vals if v["players"] <= res["config"].get("parking_min_tracks", 3)]
        out.append(f"`R-PARKING` {len(vals)} parking values ({', '.join(f'{v['axis']} = {v['value_m']:+g} m: {v['players']} players' for v in vals)}), {len(pv)} parked runs."
                   + (f" {len(few)} of them rest on the minimum number of players ({res['config'].get('parking_min_tracks', 3)}); at a coordinate resolution of "
                      f"{res.get('coordinate_resolution_m')} m frozen tracks side by side can share a value by coincidence." if few else ""))
    return out


