def _table(rows: list[list], header: list[str]) -> str:
    esc = lambda c: str(c).replace("|", "\\|")  # noqa: E731
    out = ["| " + " | ".join(esc(h) for h in header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _pct(a, b, nd=2):
    return f"{100.0 * a / b:.{nd}f} %" if b else "-"


def _f(v, fmt: str) -> str:
    return "-" if v is None else format(v, fmt)


def _n(v, fmt: str) -> str:
    """Like ``_f`` but also for NaN: values a provider does not supply."""
    return "not supplied" if v is None or v != v else format(v, fmt)


def _clock(period: int, s: float | None) -> str:
    if s is None:
        return "-"
    base = 45 * 60 if period == 2 else 0
    t = base + s
    return f"{int(t // 60):02d}:{int(t % 60):02d}"


def _kv(d: dict) -> str:
    return ", ".join(f"{k} {v}" for k, v in d.items()) or "-"


def score_text(d: dict) -> str:
    """Clearance score distribution as "3 of 7: n clearances"."""
    return "; ".join(f"{k} of 7: {v}" for k, v in d.items()) or "-"


def _clock_of(profile: dict, period: int, iso: str | None) -> str:
    if not iso:
        return "-"
    ko = profile["kickoff_per_period"].get(str(period))
    if not ko:
        return "-"
    return _clock(period, (pd.Timestamp(iso) - pd.Timestamp(ko["kickoff_utc"])).total_seconds())


