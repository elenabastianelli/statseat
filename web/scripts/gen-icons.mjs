// Country name as in synthetic/universe/universe.json -> ISO code of the flag. Meridia is fictional: no flag.
const FLAGS = {
  Argentina: "AR",
  Brazil: "BR",
  Croatia: "HR",
  France: "FR",
  Germany: "DE",
  Ireland: "IE",
  Japan: "JP",
  Netherlands: "NL",
  Nigeria: "NG",
  Norway: "NO",
  Poland: "PL",
  Scotland: "GB-SCT",
  Senegal: "SN",
  "South Korea": "KR",
};

const dir = new URL("../node_modules/@fluentui/svg-icons/icons/", import.meta.url);
const lines = [
  "// Generated by scripts/gen-icons.mjs from Fluent UI System Icons (Microsoft, MIT licence). Do not edit.",
  "export const ICON_PATHS = {",
];
for (const [name, file] of Object.entries(ICONS)) {
  const svg = readFileSync(new URL(`${file}.svg`, dir), "utf8");
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`no path in ${file}`);
  lines.push(`  ${name}: ${JSON.stringify(paths)},`);
}
lines.push("} as const;", "", "export type IconName = keyof typeof ICON_PATHS;", "");
writeFileSync(fileURLToPath(new URL("../src/components/icons.generated.ts", import.meta.url)), lines.join("\n"));
console.log(`wrote ${Object.keys(ICONS).length} icons`);

const flagDir = new URL("../node_modules/country-flag-icons/3x2/", import.meta.url);
const flagLines = [
  "// Generated by scripts/gen-icons.mjs from country-flag-icons (MIT licence). Do not edit.",
  "export const FLAG_URIS: Record<string, string> = {",
];
for (const [country, code] of Object.entries(FLAGS)) {
  const svg = readFileSync(new URL(`${code}.svg`, flagDir), "utf8").trim();
  flagLines.push(`  ${JSON.stringify(country)}: ${JSON.stringify(`data:image/svg+xml,${encodeURIComponent(svg)}`)},`);
}
flagLines.push("};", "");
writeFileSync(fileURLToPath(new URL("../src/components/flags.generated.ts", import.meta.url)), flagLines.join("\n"));
console.log(`wrote ${Object.keys(FLAGS).length} flags`);
